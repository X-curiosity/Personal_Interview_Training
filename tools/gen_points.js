#!/usr/bin/env node
/* tools/gen_points.js — regenerates api/_points.js from the problem packs so the
   server scores solves with exactly the same ids and weights as the client.
   Run after adding or removing problems: node tools/gen_points.js */
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
let source = fs.readFileSync(path.join(ROOT, "assets/js/data.js"), "utf8");
for (const file of fs.readdirSync(path.join(ROOT, "assets/js/data")).sort()) {
  if (!file.endsWith(".js")) continue;
  source += "\n" + fs.readFileSync(path.join(ROOT, "assets/js/data", file), "utf8");
}
source += "\n;globalThis.__P = PROBLEMS;";
const context = vm.createContext({});
vm.runInContext(source, context);
const problems = context.__P;

const map = {};
for (const p of problems) {
  if (map[p.id]) throw new Error("duplicate id: " + p.id);
  map[p.id] = p.difficulty;
}

const out = `/* Generated by tools/gen_points.js from the problem packs: id -> difficulty.
   Do not edit by hand; run "npm run points" after changing problems. */
"use strict";

const DIFF = ${JSON.stringify(map)};

const POINTS = { easy: 1, medium: 3, hard: 5, expert: 8 };

function pointsFor(ids) {
  let pts = 0, expert = 0, hard = 0, medium = 0, easy = 0, unknown = 0;
  for (const id of ids) {
    const d = DIFF[id];
    if (!d) { unknown++; continue; }
    pts += POINTS[d] || 0;
    if (d === "expert") expert++;
    else if (d === "hard") hard++;
    else if (d === "medium") medium++;
    else easy++;
  }
  return { points: pts, expert, hard, medium, easy, solved: ids.length - unknown, unknown };
}

const VALID_IDS = new Set(Object.keys(DIFF));

module.exports = { DIFF, POINTS, pointsFor, VALID_IDS };
`;
fs.writeFileSync(path.join(ROOT, "api/_points.js"), out);
console.log("api/_points.js regenerated:", Object.keys(map).length, "problems");
