#!/usr/bin/env node
/* tools/test_python_harness.js — verifies the Python runner harness that wraps
   solutions and hidden tests. The harness source is generated by
   assets/js/runner.js and executed here with a real CPython interpreter, which
   is the same language runtime Pyodide provides in the browser.
   Run: node tools/test_python_harness.js */
"use strict";

const assert = require("assert");
const fs = require("fs");
const os = require("os");
const path = require("path");
const vm = require("vm");
const { spawnSync } = require("child_process");

const ROOT = path.join(__dirname, "..");

/* ---------- load the browser script in a stub page ---------- */
function loadRunner() {
  const context = vm.createContext({
    window: {},
    document: {
      createElement: () => ({ set src(v) {}, set onload(v) {} }),
      head: { appendChild() {} }
    },
    PIT_CONFIG: {},
    TextEncoder,
    btoa
  });
  vm.runInContext(fs.readFileSync(path.join(ROOT, "assets/js/runner.js"), "utf8"), context);
  return context.window.PIT_RUNNER;
}

const RUNNER = loadRunner();
assert.strictEqual(typeof RUNNER.buildPythonHarness, "function", "harness builder exported");

/* ---------- run a generated harness under CPython ---------- */
const dir = fs.mkdtempSync(path.join(os.tmpdir(), "pit-harness-"));

function runHarness(code, tests) {
  const file = path.join(dir, "harness.py");
  fs.writeFileSync(file, RUNNER.buildPythonHarness(code, tests));
  const wrapper = path.join(dir, "run.py");
  fs.writeFileSync(wrapper, [
    "import sys",
    "namespace = {}",
    "with open(sys.argv[1], 'r', encoding='utf-8') as handle:",
    "    source = handle.read()",
    "exec(compile(source, 'hidden_tests.py', 'exec'), namespace)",
    "print('PIT_OK=' + ('1' if namespace['_pit_ok'] else '0'))"
  ].join("\n"));
  const result = spawnSync("python3", [wrapper, file], { encoding: "utf8", timeout: 60000 });
  if (result.error) throw result.error;
  const output = (result.stdout || "") + (result.stderr || "");
  const match = /PIT_OK=([01])/.exec(output);
  assert(match, "harness must report a verdict, got:\n" + output);
  return { ok: match[1] === "1", output };
}

/* ---------------- passing solution ---------------- */
let r = runHarness(
  "def twice(x):\n    return x * 2\n",
  "assert twice(3) == 6\nassert twice(-2) == -4\n"
);
assert.strictEqual(r.ok, true, "correct solution passes");
assert.match(r.output, /ALL TESTS PASSED/, "success message shown");
assert.doesNotMatch(r.output, /Traceback/, "no Python internals in the success output");

/* ---------------- failing check, precise report ---------------- */
r = runHarness(
  "def twice(x):\n    return x + 2\n",
  "assert twice(3) == 6\nassert twice(-2) == 0\n"
);
assert.strictEqual(r.ok, false, "wrong result fails");
assert.match(r.output, /A check failed/, "explains it is a check, not a compile error");
assert.match(r.output, /line 1 of the hidden test suite/, "names the failing test line");
assert.match(r.output, /assert twice\(3\) == 6/, "quotes the failing check");
assert.match(r.output, /AssertionError/, "names the exception");
assert.doesNotMatch(r.output, /_pyodide|_base\.py/, "no Pyodide internals");

r = runHarness(
  "def twice(x):\n    return x * 2\n",
  "assert twice(3) == 6\nassert twice(-2) == 5\n"
);
assert.strictEqual(r.ok, false);
assert.match(r.output, /line 2 of the hidden test suite/, "second failing line located");

/* ---------------- unfinished starter ---------------- */
r = runHarness(
  "def solve(x):\n    raise NotImplementedError\n",
  "assert solve(1) == 1\n"
);
assert.strictEqual(r.ok, false);
assert.match(r.output, /NotImplementedError/, "starter error named");
assert.match(r.output, /your code raised/i, "attributes the error to the solution");

/* ---------------- syntax error is labelled as one ---------------- */
r = runHarness("def broken(:\n    pass\n", "assert broken() == 1\n");
assert.strictEqual(r.ok, false);
assert.match(r.output, /does not compile/, "syntax errors say the code does not compile");
assert.match(r.output, /SyntaxError/, "syntax error named");

/* ---------------- runtime error names the line ---------------- */
r = runHarness(
  "def solve(x):\n    return missing_name + x\n",
  "assert solve(1) == 1\n"
);
assert.strictEqual(r.ok, false);
assert.match(r.output, /NameError/, "runtime error named");
assert.match(r.output, /line 2/, "runtime error line reported");

/* ---------------- printing the marker cannot fake a pass ---------------- */
r = runHarness(
  "def twice(x):\n    return x + 2\nprint('ALL TESTS PASSED')\n",
  "assert twice(3) == 6\n"
);
assert.strictEqual(r.ok, false, "a printed success marker must not count as a pass");

/* ---------------- tests that print a marker but fail stay failures ------- */
r = runHarness(
  "def twice(x):\n    return 0\n",
  "print('ALL TESTS PASSED')\nassert twice(3) == 6\n"
);
assert.strictEqual(r.ok, false, "marker printed by the tests does not hide a failure");

/* ---------------- awkward source survives the trip ---------------- */
r = runHarness(
  "def greet(name):\n    return 'hej ' + name  # åäö ünïcode\n",
  "assert greet('värld') == 'hej värld'\nassert '\\n' not in greet('x')\n"
);
assert.strictEqual(r.ok, true, "unicode and escapes survive base64 encoding");

/* ---------------- tests keep their own stdout ---------------- */
r = runHarness(
  "def f():\n    print('hello from solution')\n    return 1\n",
  "assert f() == 1\n"
);
assert.strictEqual(r.ok, true);
assert.match(r.output, /hello from solution/, "solution output is preserved");

fs.rmSync(dir, { recursive: true, force: true });
console.log("python harness OK — failures located, markers cannot fake a pass");
